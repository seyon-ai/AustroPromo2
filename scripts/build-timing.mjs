// Probes every VO clip with ffprobe and writes src/timing.ts.
// Scene start frames and durations are derived from the measured VO lengths,
// never hardcoded: each scene lasts at least its target window and always
// fits its VO clip (lead + voice + tail).
import {execFileSync} from 'node:child_process';
import {writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import ffprobeStatic from 'ffprobe-static';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FPS = 30;
const LEAD_SEC = 0.12; // silence before each VO line inside its scene
const TAIL_SEC = 0.35; // breathing room after the VO line before the next cut

// Target (minimum) length of each scene in seconds, from the shot list.
const TARGET_SEC = [4, 5, 8.5, 5, 8, 9, 8, 7];
const SCENE_NAMES = [
  'Scene01Noise', 'Scene02Logo', 'Scene03Arena', 'Scene04Kingboard',
  'Scene05Panels', 'Scene06Var', 'Scene07Store', 'Scene08Final',
];

const probe = (file) => {
  const out = execFileSync(ffprobeStatic.path, [
    '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file,
  ]).toString().trim();
  return Number(out);
};

const vo = [];
for (let i = 1; i <= 8; i++) {
  const name = String(i).padStart(2, '0');
  const file = join(root, 'public', 'vo', `${name}.mp3`);
  const sec = probe(file);
  vo.push({name, sec, frames: Math.ceil(sec * FPS)});
}

const scenes = [];
let cursor = 0;
for (let i = 0; i < 8; i++) {
  const need = Math.round((LEAD_SEC + vo[i].sec + TAIL_SEC) * FPS);
  const target = Math.round(TARGET_SEC[i] * FPS);
  const duration = Math.max(target, need);
  scenes.push({
    id: SCENE_NAMES[i],
    from: cursor,
    duration,
    voFrom: cursor + Math.round(LEAD_SEC * FPS), // VO starts this many frames into the scene
    voFrames: vo[i].frames,
    voSec: Number(vo[i].sec.toFixed(3)),
  });
  cursor += duration;
}
const TOTAL = cursor;
const FINAL_HOLD = 2 * FPS;

const fmt = (n) => String(n);
const src = `// AUTO-GENERATED by scripts/build-timing.mjs from the measured VO durations.
// Re-run \`npm run build:timing\` after changing any file in public/vo/.
export const FPS = ${FPS};
export const WIDTH = 1920;
export const HEIGHT = 1080;
export const TOTAL_FRAMES = ${fmt(TOTAL)};
export const FINAL_HOLD_FRAMES = ${fmt(FINAL_HOLD)};

export const VO = {
${vo.map((v) => `  '${v.name}': {file: 'vo/${v.name}.mp3', seconds: ${v.sec.toFixed(3)}, frames: ${v.frames}},`).join('\n')}
} as const;

export const SCENES = {
${scenes.map((s) => `  ${s.id}: {from: ${s.from}, duration: ${s.duration}, voFrom: ${s.voFrom}, voFrames: ${s.voFrames}},`).join('\n')}
} as const;

export const SCENE_ORDER = [
${scenes.map((s) => `  SCENES.${s.id},`).join('\n')}
] as const;
`;
mkdirSync(join(root, 'src'), {recursive: true});
writeFileSync(join(root, 'src', 'timing.ts'), src);
console.log(JSON.stringify({total_frames: TOTAL, total_seconds: TOTAL / FPS, scenes, vo}, null, 2));
